let currentLang = 'es';

// ═══ API pública ══════════════════════════════

function readCookie(name) {
  try {
    const m = document.cookie.match(new RegExp('(?:^|; )' + name + '=([^;]*)'));
    return m ? decodeURIComponent(m[1]) : null;
  } catch (_) { return null; }
}

export function initLanguage() {
  let lang = 'es';
  // 1) Cookie (fuente de verdad compartida con Flask)
  const ck = readCookie('lang');
  if (ck && messages[ck]) {
    lang = ck;
  } else {
    // 2) localStorage (cache del editor, retrocompatibilidad)
    try {
      const raw = localStorage.getItem('ardublock:settings');
      if (raw) {
        const s = JSON.parse(raw);
        if (s.language && messages[s.language]) lang = s.language;
      }
    } catch (_) { /* usar default */ }
  }

  currentLang = lang;
  document.documentElement.lang = lang;
  const msgs = messages[lang];
  Object.assign(Blockly.Msg, msgs);
}

export function setLanguage(lang) {
  if (!messages[lang]) return;
  try {
    document.cookie = 'lang=' + lang + '; path=/; max-age=31536000; SameSite=Lax';
    const raw = localStorage.getItem('ardublock:settings') || '{}';
    const s = JSON.parse(raw);
    s.language = lang;
    localStorage.setItem('ardublock:settings', JSON.stringify(s));
  } catch (_) { /* ignorar */ }
  location.reload();
}

export function t(key, params) {
  const msgs = messages[currentLang];
  let s = msgs[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split('{' + k + '}').join(String(v));
    }
  }
  return s;
}

export function getLanguage() {
  return currentLang;
}

export function applyDOMLanguage() {
  const langMsgs = messages[currentLang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (langMsgs[key]) el.textContent = langMsgs[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (langMsgs[key]) el.placeholder = langMsgs[key];
  });
}
// Side-effect: inicializar idioma al importar este módulo
initLanguage();
